import { docMeta } from "../meta";
import { B, DocSection, DocSubsection, LI, Note, P, UL } from "../primitives";

const { title, parts } = docMeta.verification;

export function VerificationSection() {
    return (
        <DocSection title={title}>
            <Note>
                Answers are generated by a large language model (LLM). They have not been systematically evaluated, and
                they are not legal advice. Verify anything you rely on against the original law.
            </Note>

            <DocSubsection title={parts.checked}>
                <UL>
                    <LI>
                        <B>Country records.</B> The country records were reviewed against published sources in October
                        2026, including the African Union’s official Malabo Convention status list. Records that were
                        out of date were corrected.
                    </LI>
                    <LI>
                        <B>Source links.</B> The links in the Sources library were checked in October 2026, and broken
                        or misdescribed links were fixed.
                    </LI>
                    <LI>
                        <B>Reference data files.</B> Automated tests in the backend repository check the country data
                        files: that every African Union member has a record, that statuses are valid, and that links are
                        well formed.
                    </LI>
                    <LI>
                        <B>Guardrails.</B> Several safeguards are built into the pipeline:
                        <UL>
                            <LI>an LLM-based scope guardrail declines off-topic questions on public documents;</LI>
                            <LI>
                                the prompt instructs the model to stay grounded in the retrieved context;
                            </LI>
                            <LI>answers that draw on web results are instructed to say so.</LI>
                        </UL>
                    </LI>
                </UL>
                <P>
                    These safeguards rely on an LLM’s judgement or on instructions given to it, so they cannot be
                    guaranteed on every question or answer.
                </P>
            </DocSubsection>

            <DocSubsection title={parts.notChecked}>
                <UL>
                    <LI>
                        <B>No systematic evaluation.</B> Retrieval quality, the faithfulness of answers to the retrieved
                        text, the accuracy of citations and the correctness of answers have not been formally measured.
                        Check important points against the original law or document before relying on an answer.
                    </LI>
                    <LI>
                        <B>Automatic extraction is not reviewed.</B> The country, title and description detected for
                        each document are not manually checked.
                    </LI>
                    <LI>
                        <B>Some classifications rest on secondary sources.</B> Where a law was reported by news or a
                        legal guide, it may not have been confirmed against the text of the law itself.
                    </LI>
                </UL>
            </DocSubsection>

            <DocSubsection title={parts.limitations}>
                <UL>
                    <LI>
                        <B>Hallucination.</B> An LLM can state something that the sources do not support, including a
                        wrong citation, even when it is instructed to stay grounded.
                    </LI>
                    <LI>
                        <B>Counts can be incomplete.</B> An answer draws on a limited number of chunks: for a counting
                        question, at most 12 from the document search by default. That cannot cover every country, so use
                        the maps and country indicators for continent-wide counts.
                    </LI>
                    <LI>
                        <B>Chunking can split provisions.</B> Chunks do not follow legal structure, and PDF chunks stop
                        at page ends, so a retrieved chunk may hold only part of an article.
                    </LI>
                    <LI>
                        <B>Keyword search is limited.</B> The keyword part of hybrid search uses English stemming and
                        stop words, and in the current version it does not give rare words extra weight (BM25’s inverse
                        document frequency).
                    </LI>
                    <LI>
                        <B>Coverage depends on the collection.</B> An answer can only be as complete and current as the
                        documents it draws on. Laws are amended, and new instruments are adopted.
                    </LI>
                    <LI>
                        <B>Check that the answer is about the right country.</B> When no evidence is found for a named
                        country, the search widens, so an answer may draw on general material or other countries’ laws.
                        Check that the answer is about the country’s own law, and confirm it against the text of that
                        law.
                    </LI>
                    <LI>
                        <B>Web results are not reviewed.</B> Answers that include web results rely on external sources
                        the project team has not checked.
                    </LI>
                    <LI>
                        <B>Indicators simplify.</B> One category per indicator can hide nuance, such as sector-specific
                        rules or laws that are enacted but not yet in force. Legislation status records that a law has
                        been enacted, not whether a regulator is operating or enforcing it. Use the reference sources to
                        see the detail.
                    </LI>
                    <LI>
                        <B>Not legal advice.</B> The Policy Analyzer is a research and information tool. It does not
                        replace advice from a qualified legal professional.
                    </LI>
                </UL>
            </DocSubsection>
        </DocSection>
    );
}
